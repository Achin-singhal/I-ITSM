-- Add managed category records while retaining the original category string as
-- an incident display/history snapshot. Existing incidents are linked in place.
CREATE TABLE incident_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    category_key VARCHAR(64) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO incident_categories(name, category_key, active)
SELECT MIN(TRIM(category)), LOWER(TRIM(category)), TRUE
FROM incidents
WHERE category IS NOT NULL AND TRIM(category) <> ''
GROUP BY LOWER(TRIM(category));

