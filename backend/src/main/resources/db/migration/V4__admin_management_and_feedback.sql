ALTER TABLE incidents ADD COLUMN category_id BIGINT;
UPDATE incidents i SET category_id = c.id
FROM incident_categories c WHERE LOWER(TRIM(i.category)) = c.category_key;
ALTER TABLE incidents ADD CONSTRAINT fk_incidents_category
    FOREIGN KEY (category_id) REFERENCES incident_categories(id);
CREATE INDEX ix_incidents_category_id ON incidents(category_id);

CREATE TABLE incident_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL UNIQUE REFERENCES incidents(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comments VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_incident_feedback_employee_created ON incident_feedback(employee_id, created_at DESC);
