-- Add a managed service catalog while retaining historical affected_service text.
CREATE TABLE it_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    service_key VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(1000) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Preserve existing service labels as active catalog entries so existing installations
-- have selectable values immediately after migration. Keep one built-in fallback.
INSERT INTO it_services(name, service_key, description, active)
SELECT MIN(TRIM(affected_service)), LOWER(TRIM(affected_service)),
       'Imported from existing incident service labels', TRUE
FROM incidents
WHERE affected_service IS NOT NULL AND TRIM(affected_service) <> ''
GROUP BY LOWER(TRIM(affected_service));

INSERT INTO it_services(name, service_key, description, active)
SELECT 'General IT Service', 'general it service', 'Default service', TRUE
WHERE NOT EXISTS (SELECT 1 FROM it_services WHERE service_key = 'general it service');

ALTER TABLE incidents ADD COLUMN service_id BIGINT;
ALTER TABLE incidents ADD CONSTRAINT fk_incidents_it_service
    FOREIGN KEY (service_id) REFERENCES it_services(id);
CREATE INDEX ix_incidents_service_id ON incidents(service_id);

UPDATE incidents i
SET service_id = s.id
FROM it_services s
WHERE LOWER(TRIM(i.affected_service)) = s.service_key;
